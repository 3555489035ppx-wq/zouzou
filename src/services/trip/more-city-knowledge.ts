import type { CityAdditionalSpec } from './cityKnowledge.expanded'

type PlaceEntry = [name: string, area: string, tags: string[], summary?: string, category?: 'attraction' | 'activity']
type FoodEntry = [name: string, area: string, tags: string[], dietaryTags?: string[], category?: 'food' | 'restaurant', summary?: string]
type MoreCityCatalog = {
  center: [number, number]
  landmarks: PlaceEntry[]
  local: PlaceEntry[]
  foods: FoodEntry[]
}

const sourceFor = (city: string, name: string) => ({
  label: `地图检索：${city}${name}`,
  url: `https://uri.amap.com/search?keyword=${encodeURIComponent(`${city} ${name}`)}&src=zouzou&callnative=0`,
  kind: 'amap' as const,
  checkedAt: '2026-09-02',
})

const placeSummary = (city: string, name: string, category: 'attraction' | 'activity', summary?: string) => summary
  ?? (category === 'attraction'
    ? `${name}是${city}的代表性地点，优先看核心建筑、主展线或主景观，不把外围重复景观塞进同一天。`
    : `把${name}作为${city}的当地体验，留出慢走、拍照和临时进店的弹性。`)

const foodSummary = (city: string, name: string, summary?: string) => summary
  ?? `在${city}找${name}，先看当天菜单和店内客流；对忌口用户要现场确认配料、汤底和调味。`

function buildSpecs(city: string, catalog: MoreCityCatalog): CityAdditionalSpec[] {
  const specs: CityAdditionalSpec[] = []
  catalog.landmarks.forEach(([name, area, tags, summary, category = 'attraction']) => {
    specs.push({
      name,
      category,
      area,
      tags: [...new Set([...tags, category === 'attraction' ? '知名景点' : '本地体验'])],
      summary: placeSummary(city, name, category, summary),
      durationMinutes: category === 'attraction' ? 120 : 80,
      price: category === 'attraction' ? { min: 0, max: 80, unit: 'ticket', note: '票价与预约按出行当天公告确认' } : { min: 0, max: 40, unit: 'person', note: '现场消费按当天菜单确认' },
      source: sourceFor(city, name),
    })
  })
  catalog.local.forEach(([name, area, tags, summary]) => {
    specs.push({
      name,
      category: 'activity',
      area,
      tags: [...new Set([...tags, '本地人项目'])],
      summary: placeSummary(city, name, 'activity', summary),
      venueName: name,
      address: `${city}${area}`,
      searchKeyword: `${city} ${name}`,
      durationMinutes: 75,
      price: { min: 0, max: 60, unit: 'person', note: '街区活动与现场消费按当天情况确认' },
      source: sourceFor(city, name),
    })
  })
  catalog.foods.forEach(([name, area, tags, dietaryTags = [], category = 'food', summary]) => {
    specs.push({
      name,
      category,
      area,
      tags: [...new Set(['菜品线索', '本地小吃', '本地美食', ...(category === 'restaurant' ? ['本地餐馆'] : []), ...tags])],
      dietaryTags,
      summary: foodSummary(city, name, summary),
      menuHighlights: [name],
      searchKeyword: `${city} ${name}`,
      durationMinutes: category === 'restaurant' ? 75 : 35,
      price: {state: 'unknown', min: 0, max: 0, unit: 'person', note: '仅为菜品线索，具体门店与菜单报价尚未取得'},
      source: sourceFor(city, name),
    })
  })
  return specs
}

