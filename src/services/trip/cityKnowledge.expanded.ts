import type { KnowledgeCategory, KnowledgePrice, KnowledgeSource } from './cityKnowledge'

export type CityAdditionalSpec = {
  name: string
  category: KnowledgeCategory
  area: string
  tags: string[]
  summary?: string
  coordinates: [number, number]
  /** A concrete venue name is required before food enters a generated route. */
  venueName?: string
  address?: string
  menuHighlights?: string[]
  searchKeyword?: string
  durationMinutes?: number
  price?: KnowledgePrice
  dietaryTags?: string[]
  opening?: {
    from: string
    to: string
    label: string
    closedWeekdays?: number[]
  }
  source?: KnowledgeSource
}

const place = (
  category: 'attraction' | 'activity',
  name: string,
  area: string,
  tags: string[],
  summary: string,
  coordinates: [number, number],
  durationMinutes = category === 'attraction' ? 120 : 90,
  price?: KnowledgePrice,
): CityAdditionalSpec => ({ category, name, area, tags, summary, coordinates, durationMinutes, price })

const attraction = (
  name: string,
  area: string,
  tags: string[],
  summary: string,
  coordinates: [number, number],
  durationMinutes = 120,
  price?: KnowledgePrice,
) => place('attraction', name, area, tags, summary, coordinates, durationMinutes, price)

const activity = (
  name: string,
  area: string,
  tags: string[],
  summary: string,
  coordinates: [number, number],
  durationMinutes = 90,
  price?: KnowledgePrice,
) => place('activity', name, area, tags, summary, coordinates, durationMinutes, price)

const meal = (
  category: 'food' | 'restaurant',
  name: string,
  area: string,
  tags: string[],
  summary: string,
  coordinates: [number, number],
  dietaryTags: string[] = [],
): CityAdditionalSpec => ({ category, name, area, tags, summary, coordinates, durationMinutes: category === 'restaurant' ? 75 : 35, dietaryTags })

const snack = (
  name: string,
  area: string,
  tags: string[],
  summary: string,
  coordinates: [number, number],
  dietaryTags: string[] = [],
) => meal('food', name, area, tags, summary, coordinates, dietaryTags)

const restaurant = (
  name: string,
  area: string,
  tags: string[],
  summary: string,
  coordinates: [number, number],
  dietaryTags: string[] = [],
) => meal('restaurant', name, area, tags, summary, coordinates, dietaryTags)

