const fallbackZone = (city: string, name: string, area: string): RouteZoneSpec => {
  const text = `${name} ${area}`
  return /县|远郊|周边|大峡谷|石林|龙脊|亚布力|木兰天池/.test(text)
    ? { name: `${city}周边远线`, order: 4, terms: [] }
    : { name: `${city}城市核心线`, order: 1, terms: [] }
}

export function getCityRouteZone(city: string, name: string, area: string): RouteZoneSpec {
  const text = `${name} ${area}`
  const matches = (cityRouteSpecs[city] ?? [])
    .flatMap((zone) => zone.terms.filter((term) => text.includes(term)).map((term) => ({ zone, term })))
    .sort((left, right) => right.term.length - left.term.length || left.zone.order - right.zone.order)
  return matches[0]?.zone ?? fallbackZone(city, name, area)
}
